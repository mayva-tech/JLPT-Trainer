/**
 * Furigana for every kanji in the nuance notes, read in context by kuromoji
 * and written to src/data/nuanceFurigana.generated.ts.
 *
 *   npm run nuance-furigana
 *
 * Re-run after adding or editing nuance text (nuanceFurigana.test.ts fails
 * until you do).
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import kuromoji, { type IpadicFeatures, type Tokenizer } from "kuromoji";
import { allNuanceTexts } from "../src/data/nuanceTexts";
import { KANJI_RUN_RE, encodeRunReadings, kanjiRunKey } from "../src/utils/nuanceFurigana";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const KANJI_RE = /[\p{Script=Han}々〆]/u;
const KANA_RE = /[\p{Script=Hiragana}\p{Script=Katakana}ー]/u;

function toHiragana(text: string): string {
  return text.replace(/[\u30a1-\u30f6]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0x60));
}

function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function buildTokenizer(): Promise<Tokenizer<IpadicFeatures>> {
  return new Promise((done, fail) => {
    kuromoji
      .builder({ dicPath: resolve(root, "node_modules/kuromoji/dict") })
      .build((err, tokenizer) => (err ? fail(err) : done(tokenizer)));
  });
}

type Piece = { start: number; length: number; reading: string };

/** Furigana for each kanji run inside one token: 取り扱い/とりあつかい → 取:と, 扱:あつか. */
function tokenPieces(token: IpadicFeatures, start: number): Piece[] {
  const surface = token.surface_form;
  if (!KANJI_RE.test(surface) || !token.reading || token.reading === "*") return [];
  const runs: { start: number; text: string }[] = [];
  let pattern = "^";
  for (const m of surface.matchAll(/[\p{Script=Han}々〆]+|./gu)) {
    const ch = m[0];
    if (KANJI_RE.test(ch)) {
      runs.push({ start: m.index ?? 0, text: ch });
      pattern += "(.+?)";
    } else if (KANA_RE.test(ch)) {
      pattern += escapeRegExp(toHiragana(ch));
    } else {
      return [];
    }
  }
  const match = new RegExp(`${pattern}$`, "u").exec(toHiragana(token.reading));
  if (!match) return [];
  return runs.map((run, i) => ({
    start: start + run.start,
    length: run.text.length,
    reading: match[i + 1]!,
  }));
}

type Votes = Map<string, Map<string, number>>;

function vote(votes: Votes, key: string, value: string): void {
  const tally = votes.get(key) ?? new Map<string, number>();
  tally.set(value, (tally.get(value) ?? 0) + 1);
  votes.set(key, tally);
}

function majority(tally: Map<string, number>): string {
  return [...tally].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))[0]![0];
}

async function main(): Promise<void> {
  const tokenizer = await buildTokenizer();
  const votes: Votes = new Map();
  const withBefore: Votes = new Map();
  let runs = 0;
  let unread = 0;

  for (const text of allNuanceTexts()) {
    const pieces: Piece[] = [];
    let offset = 0;
    for (const token of tokenizer.tokenize(text)) {
      pieces.push(...tokenPieces(token, offset));
      offset += token.surface_form.length;
    }
    for (const m of text.matchAll(KANJI_RUN_RE)) {
      runs += 1;
      const start = m.index ?? 0;
      const end = start + m[0].length;
      const inside = pieces.filter((p) => p.start >= start && p.start + p.length <= end);
      const covered = inside.reduce((sum, p) => sum + p.length, 0);
      if (covered !== m[0].length || inside[0]?.start !== start) {
        unread += 1;
        continue;
      }
      const key = kanjiRunKey(m[0], text[end] ?? "");
      const value = encodeRunReadings(inside.map((p) => [[...text.slice(p.start, p.start + p.length)].length, p.reading]));
      vote(votes, key, value);
      vote(withBefore, `${text[start - 1] ?? "^"}${key}`, value);
    }
  }

  const table: [string, string][] = [];
  const split: string[] = [];
  for (const [key, tally] of votes) {
    const reading = majority(tally);
    table.push([key, reading]);
    if (tally.size > 1) split.push(`${key} ${[...tally].map(([v, n]) => `${v}×${n}`).join(" ")}`);
  }
  // Where the character before the run flips the reading, keep that too.
  for (const [key, tally] of withBefore) {
    const reading = majority(tally);
    if (reading !== majority(votes.get(key.slice(1))!)) table.push([key, reading]);
  }
  table.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

  const body = table.map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`).join("\n");
  writeFileSync(
    resolve(root, "src/data/nuanceFurigana.generated.ts"),
    `// Generated by scripts/generateNuanceFurigana.ts — do not edit by hand.\n` +
      `export const NUANCE_FURIGANA: Readonly<Record<string, string>> = {\n${body}\n};\n`,
    "utf8"
  );
  console.log(`${table.length} entries; ${runs} kanji runs, ${unread} without a reading.`);
  if (split.length) console.log(`Readings that differ by context (majority kept):\n${split.join("\n")}`);
}

void main();
